import { ExactConcordiumScheme as Client } from '@x402/concordium/exact/client';
import { ExactConcordiumScheme as Server } from '@x402/concordium/exact/server';
import { ExactConcordiumScheme as Facil } from '@x402/concordium/exact/facilitator';
import { CONCORDIUM_TESTNET_CAIP2, toConcordiumFacilitatorSigner } from '@x402/concordium';
import { buildBasicAccountSigner, AccountAddress } from '@concordium/web-sdk';
import fs from 'fs';
import { wallet } from './lib.mjs';
const w = wallet();
const acc = n => JSON.parse(fs.readFileSync(`account${n}.json`)).address;
const key = n => w.getAccountSigningKey(0,0,n).toString('hex');
const NET = CONCORDIUM_TESTNET_CAIP2;
const facSigner = toConcordiumFacilitatorSigner(acc(0), key(0), {host:'grpc.testnet.concordium.com', port:20000, useTls:true});
const fac = new Facil({ signer: facSigner, finalizationTimeoutMs: 60000 });
const server = new Server();
const asset = await server.parsePrice({amount:'500000', asset:'CCD'}, NET);
let req = { scheme:'exact', network:NET, payTo: acc(1), amount: asset.amount, asset: asset.asset, maxTimeoutSeconds: 300, extra: asset.extra||{} };
req = await server.enhancePaymentRequirements(req, {x402Version:2, scheme:'exact', network:NET, extra: fac.getExtra(NET)}, []);
console.log('requirements', JSON.stringify(req));
const client = new Client({ accountAddress: AccountAddress.fromBase58(acc(2)), signer: buildBasicAccountSigner(key(2)) }, {grpcUrl:'grpc.testnet.concordium.com:20000', useTls:true});
const p = await client.createPaymentPayload(2, req);
const payload = { ...p, accepted: req, resource: {url:'https://x/api/review'} };
console.log('payload keys', Object.keys(p.payload));
const v = await fac.verify(payload, req); console.log('verify', JSON.stringify(v));
const s = await fac.settle(payload, req); console.log('settle', JSON.stringify(s));
