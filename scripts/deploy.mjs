import { createCredentialPayload, signCredentialTransaction, TransactionExpiry, getAccountAddress, serializeCredentialDeploymentPayload } from '@concordium/web-sdk';
import { ConcordiumGRPCNodeClient, credentials } from '@concordium/web-sdk/nodejs';
import fs from 'fs';
import { WP, seedHex, wallet, j } from './lib.mjs';
const client = new ConcordiumGRPCNodeClient('grpc.testnet.concordium.com', 20000, credentials.createSsl(), {timeout:30000});
const g = await client.getCryptographicParameters();
const ips = await j(WP+'/v1/ip_info');
const ip = ips.find(x=>x.ipInfo.ipIdentity===0);
const idObject = JSON.parse(fs.readFileSync('identity.json')).token.identityObject.value;
const CN=Number(process.argv[2]||0);
const expiry = TransactionExpiry.futureMinutes(30);
const req = createCredentialPayload({ ipInfo: ip.ipInfo, globalContext: g, arsInfos: ip.arsInfos, idObject, revealedAttributes: [], credNumber: CN, seedAsHex: seedHex(), net:'Testnet', identityIndex:0 }, expiry);
const w = wallet();
const signingKey = w.getAccountSigningKey(0, 0, CN).toString('hex');
const sig = await signCredentialTransaction(req, signingKey);
const raw = serializeCredentialDeploymentPayload([sig], req);
const ok = await client.sendCredentialDeploymentTransaction(raw, expiry);
const addr = getAccountAddress(req.unsignedCdi.credId);
console.log('sent', ok.toString?.() ?? ok, 'address', addr.address);
fs.writeFileSync('account'+CN+'.json', JSON.stringify({address: addr.address, credId: req.unsignedCdi.credId}));
